inline constexpr int kGlyphCount = static_cast<int>(sizeof(kGlyphs) / sizeof(kGlyphs[0]));

/// The box drawn for a character that is not in the set.
inline constexpr Glyph kMissing = {'\0', {0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F}};

/// The glyph of `c` (a small letter as its capital), or kMissing.
constexpr const Glyph& Find(char c)
{
    if (c >= 'a' && c <= 'z')
    {
        c = static_cast<char>(c - 'a' + 'A');
    }
    for (const Glyph& g : kGlyphs)
    {
        if (g.c == c)
        {
            return g;
        }
    }
    return kMissing;
}

/// True when the pixel (column x, row y) of `g` is lit; x 0 .. 4 from the left, y 0 .. 6 from the top.
constexpr bool Lit(const Glyph& g, int x, int y)
{
    return x >= 0 && x < kGlyphWidth && y >= 0 && y < kGlyphHeight && ((g.rows[y] >> (kGlyphWidth - 1 - x)) & 1) != 0;
}

/// Every character of the set has its own glyph (no character twice), and every one but the space has a lit pixel.
constexpr bool SetIsSound()
{
    for (int i = 0; i < kGlyphCount; ++i)
    {
        int lit = 0;
        for (int y = 0; y < kGlyphHeight; ++y)
        {
            lit += kGlyphs[i].rows[y] != 0 ? 1 : 0;
            if (kGlyphs[i].rows[y] > 0x1F)
            {
                return false; // a sixth column
            }
        }
        if ((lit == 0) != (kGlyphs[i].c == ' '))
        {
            return false;
        }
        for (int j = i + 1; j < kGlyphCount; ++j)
        {
            if (kGlyphs[i].c == kGlyphs[j].c)
            {
                return false;
            }
        }
    }
    return true;
}
static_assert(SetIsSound(), "render/Font5x7.h: a glyph is empty, too wide or written twice");

